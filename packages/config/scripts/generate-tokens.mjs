import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const sourcePath = resolve(root, 'tokens.json');
const cssPath = resolve(root, 'src/tokens.css');
const tsPath = resolve(root, 'src/tokens.ts');
const checkOnly = process.argv.includes('--check');
const source = JSON.parse(await readFile(sourcePath, 'utf8'));

const kebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const sections = ['color', 'shadow', 'radius', 'space', 'font', 'motion', 'layout'];
const declarations = [];

for (const section of sections) {
  for (const [key, value] of Object.entries(source[section] ?? {})) {
    declarations.push(`  --wafflr-${section === 'color' ? 'color-' : section === 'shadow' ? 'shadow-' : section === 'layout' ? '' : section === 'font' ? 'font-' : section === 'motion' ? 'motion-' : section === 'radius' ? 'radius-' : 'space-'}${kebab(key)}: ${value};`);
  }
}

const css = `/* Generated from tokens.json. Do not edit this file directly. */
:root {
  color-scheme: light;
${declarations.join('\n')}
}

* { box-sizing: border-box; }
html { background: var(--wafflr-color-paper); }
body { font-family: var(--wafflr-font-body); color: var(--wafflr-color-ink); }
:focus-visible { outline: 3px solid var(--wafflr-color-coral); outline-offset: 3px; }

@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after {
    scroll-behavior: auto !important;
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
  }
}
`;

const ts = `/* Generated from tokens.json. Do not edit this file directly. */
export const tokens = ${JSON.stringify(source, null, 2)} as const;

export type WafflrColor = keyof typeof tokens.color;
export type WafflrShadow = keyof typeof tokens.shadow;
export type WafflrRadius = keyof typeof tokens.radius;
export type WafflrSpace = keyof typeof tokens.space;
export type WafflrFont = keyof typeof tokens.font;
export type WafflrMotion = keyof typeof tokens.motion;
export type WafflrLayout = keyof typeof tokens.layout;
`;

let failed = false;
for (const [path, expected] of [[cssPath, css], [tsPath, ts]]) {
  if (checkOnly) {
    let actual = '';
    try { actual = await readFile(path, 'utf8'); } catch {}
    if (actual !== expected) {
      console.error(`Out of date generated token file: ${path}`);
      failed = true;
    }
  } else {
    await writeFile(path, expected);
    console.log(`Generated ${path}`);
  }
}

if (failed) process.exitCode = 1;
