import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(here, '../tokens.source.json');
const source = JSON.parse(readFileSync(sourcePath, 'utf8'));
const outputs = [
  [resolve(here, '../src/tokens.css'), renderCss(source)],
  [resolve(here, '../src/tokens.ts'), renderTypeScript(source)],
];
const check = process.argv.includes('--check');
let stale = false;

for (const [path, expected] of outputs) {
  let actual = '';
  try {
    actual = readFileSync(path, 'utf8');
  } catch {}
  if (actual !== expected) {
    stale = true;
    if (check) console.error(`Generated token file is out of date: ${path}`);
    else writeFileSync(path, expected);
  }
}

if (check && stale) process.exit(1);
if (!check) console.log('Generated token CSS and TypeScript from tokens.source.json.');
else console.log('Design token outputs are up to date.');

function kebab(value) {
  return value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function renderCss(source) {
  const lines = [':root {', '  color-scheme: light;'];
  for (const [group, values] of Object.entries(source)) {
    for (const [name, value] of Object.entries(values)) {
      if (group === 'color') lines.push(`  --wafflr-color-${kebab(name)}: ${value};`);
      if (group === 'radius') lines.push(`  --wafflr-radius-${kebab(name)}: ${value};`);
      if (group === 'space') lines.push(`  --wafflr-space-${name}: ${value};`);
      if (group === 'shadow') lines.push(`  --wafflr-shadow-${kebab(name)}: ${value};`);
      if (group === 'font') lines.push(`  --wafflr-font-${kebab(name)}: ${value};`);
      if (group === 'motion') lines.push(`  --wafflr-motion-${kebab(name)}: ${value};`);
      if (group === 'layout') lines.push(`  --wafflr-${kebab(name)}: ${value};`);
    }
  }
  lines.push(
    '}',
    '',
    '@theme inline {',
    '  --color-page: var(--wafflr-color-page-background);',
    '  --color-surface: var(--wafflr-color-surface);',
    '  --color-brand-primary: var(--wafflr-color-action-primary);',
    '  --color-brand-accent: var(--wafflr-color-accent-primary);',
    '  --color-text-primary: var(--wafflr-color-text-primary);',
    '  --color-text-secondary: var(--wafflr-color-text-secondary);',
    '  --color-positive: var(--wafflr-color-positive);',
    '  --color-danger: var(--wafflr-color-danger);',
    '  --radius-card: var(--wafflr-radius-lg);',
    '  --font-body: var(--wafflr-font-body);',
    '  --font-display: var(--wafflr-font-display);',
    '}',
    '',
    '* { box-sizing: border-box; }',
    'html { background: var(--wafflr-color-paper); }',
    'body { font-family: var(--wafflr-font-body); color: var(--wafflr-color-ink); }',
    ':focus-visible { outline: 3px solid var(--wafflr-color-coral); outline-offset: 3px; }',
    '@media (prefers-reduced-motion: reduce) {',
    '  *, *::before, *::after { scroll-behavior: auto !important; animation-duration: 0.01ms !important; animation-iteration-count: 1 !important; transition-duration: 0.01ms !important; }',
    '}',
    '',
  );
  return lines.join(String.fromCharCode(10));
}

function renderTypeScript(source) {
  return [
    '// Generated from ../tokens.source.json. Do not edit this file directly.',
    `export const tokens = ${JSON.stringify(source, null, 2)} as const;`,
    '',
    'export type WafflrColor = keyof typeof tokens.color;',
    '',
  ].join(String.fromCharCode(10));
}
